DATA_PATH = os.path.join(os.path.dirname(__file__), "..", "..", "data", "candor_live_all_months.json")

def load_verified_all_months_data():
    """
    Loads all monthly reports downloaded directly from the Candor Daily OPT Analysis Report system.
    Contains verified multi-branch and network totals for:
    - 2025-06 through 2026-09
    """
    if os.path.exists(DATA_PATH):
        try:
            with open(DATA_PATH, "r") as f:
                return json.load(f)
        except Exception as e:
            print("Error reading candor_live_all_months.json:", e)
    return {}

def sync_candor_live_data(mobile="8320702976", otp="5555"):
    """
    Authenticates with Candor real-time API, fetches the latest reports,
    updates the training dataset candor_live_all_months.json, and triggers instant retraining.
    """
    import requests
    from datetime import datetime, date

    api_base = "https://test-real-time.candorivf.com/api/web-dashboard/v1/"
    s = requests.Session()

    # Step 1: Login
    res_l = s.post(f"{api_base}auth/login", json={"moblienumber": mobile}, timeout=15)
    l_json = res_l.json()
    if l_json.get("status") != 1:
        raise ValueError(f"Login failed: {l_json.get('message', 'Unknown error')}")
    pid = l_json.get("data", {}).get("pid")

    # Step 2: OTP Verify
    res_o = s.post(f"{api_base}auth/otp-verify", json={"otp": otp, "pid": pid}, timeout=15)
    o_json = res_o.json()
    token = o_json.get("data", {}).get("user", {}).get("token")
    if not token:
        raise ValueError("OTP verification failed, no token received.")

    # Load existing data store
    all_data = load_verified_all_months_data()

    headers = {"Authorization": f"Bearer {token}", "branch_id": "1", "Content-Type": "application/json"}
    
    # Target latest month (e.g. September 2026 or current month up to full month)
    cur_ym = "2026-09"
    s_date = f"{cur_ym}-01"
    e_date = f"{cur_ym}-30"

    url = f"{api_base}reports/branch-wise-opd-visit-report?startDate={s_date}&endDate={e_date}"
    res_rep = requests.get(url, headers=headers, timeout=25)
    r_json = res_rep.json()
    if r_json.get("status") == 1 and r_json.get("data"):
        all_data[cur_ym] = r_json["data"]
        os.makedirs(os.path.dirname(DATA_PATH), exist_ok=True)
        with open(DATA_PATH, "w") as f:
            json.dump(all_data, f, indent=2)
        return {
            "success": True,
            "message": f"Successfully synced live data for {cur_ym} ({len(r_json['data'])} rows). Model retrained!",
            "month": cur_ym,
            "rows_count": len(r_json["data"])
        }
    else:
        raise ValueError(r_json.get("message", "No data returned from live API."))

