    # Attach live tracking and rolled over next-week targets to branches
    net_week_actual = 0
    net_today_actual = 0
    net_week_shortfall = 0
    net_next_week_target = 0

    for b in branches_results:
        b_id_str = str(b['branch_id'])
        actual_week = weekly_actual_map.get(b_id_str, 0)
        actual_today = daily_actual_map.get(b_id_str, 0)

        weekly_tgt = b['weekly_target_new_opd']
        daily_tgt = b['daily_target_new_opd']

        # Shortfall calculation: how many patients were missed from this week's target?
        week_deficit = max(0, weekly_tgt - actual_week)
        day_deficit = max(0, daily_tgt - actual_today)

        # Rollover formula: Next week target = base weekly target + 50% rollover of unmet shortfall
        # (gradually spreads the unmet target so the team catches up sustainably)
        rollover_add = int(np.ceil(week_deficit * 0.5))
        next_week_target = weekly_tgt + rollover_add

        week_completion_pct = round((actual_week / max(1, weekly_tgt)) * 100, 1)
        day_completion_pct = round((actual_today / max(1, daily_tgt)) * 100, 1)

        b['tracking'] = {
            'tracking_date': latest_active_date,
            'today_actual': actual_today,
            'today_target': daily_tgt,
            'today_deficit': day_deficit,
            'today_completion_pct': day_completion_pct,
            'today_status': 'Completed' if actual_today >= daily_tgt else 'Pending',
            'current_week_actual': actual_week,
            'current_week_target': weekly_tgt,
            'current_week_deficit': week_deficit,
            'current_week_completion_pct': week_completion_pct,
            'current_week_status': 'Achieved' if actual_week >= weekly_tgt else 'Shortfall (Rolling Over)',
            'rollover_added': rollover_add,
            'next_week_target': next_week_target
        }

        net_week_actual += actual_week
        net_today_actual += actual_today
        net_week_shortfall += week_deficit
        net_next_week_target += next_week_target

    # Network-wide live tracking summary
    net_weekly_tgt = network_summary['weekly_target_new_opd']
    net_daily_tgt = network_summary['daily_target_new_opd']
    net_rollover_add = int(np.ceil(max(0, net_weekly_tgt - net_week_actual) * 0.5))

    network_summary['live_tracking'] = {
        'tracking_date': latest_active_date,
        'today_actual': net_today_actual,
        'today_target': net_daily_tgt,
        'today_deficit': max(0, net_daily_tgt - net_today_actual),
        'today_completion_pct': round((net_today_actual / max(1, net_daily_tgt)) * 100, 1),
        'today_status': 'Completed' if net_today_actual >= net_daily_tgt else 'Pending',
        'current_week_actual': net_week_actual,
        'current_week_target': net_weekly_tgt,
        'current_week_deficit': max(0, net_weekly_tgt - net_week_actual),
        'current_week_completion_pct': round((net_week_actual / max(1, net_weekly_tgt)) * 100, 1),
        'current_week_status': 'Achieved' if net_week_actual >= net_weekly_tgt else 'Shortfall',
        'rollover_added': net_rollover_add,
        'next_week_target': net_weekly_tgt + net_rollover_add
    }

    # Medication Monthly Revenue by Patient Clinical Category
    med_monthly_rev = get_medication_monthly_revenue()

    return {
        "network_summary": network_summary,
        "branches": branches_results,
        "network_monthly_history": network_monthly,
        "medication_monthly_revenue": med_monthly_rev,
        "daily_appointments_history": daily_records,
        "available_months": sorted_months
    }
