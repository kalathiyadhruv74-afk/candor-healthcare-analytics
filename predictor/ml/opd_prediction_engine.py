    latest_avail_month = sorted_months[-1] if sorted_months else '2026-09'
    active_baseline_month = selected_month if (selected_month and selected_month in all_months) else latest_avail_month

    # 3. Train ML Time-Series Momentum Model per branch
    branches_results = []
    for b_name in report_branch_names:
        hist_list = branch_records[b_name]
        bid = branch_name_to_id.get(b_name, None)
        b_city = branch_meta.get(bid, {}).get('city', 'Gujarat') if bid else 'Gujarat'
        is_main = branch_meta.get(bid, {}).get('is_main', False) if bid else (b_name == 'Varachha')

        # Find index of baseline month
        target_idx = -1
        for idx, h in enumerate(hist_list):
            if h['month'] == active_baseline_month:
                target_idx = idx
                break
        if target_idx == -1:
            target_idx = len(hist_list) - 1

        baseline_point = hist_list[target_idx]
        actual_inflow = baseline_point['total']

        # Normalization for September (28 days -> full 30 days)
        if active_baseline_month == '2026-09':
            normalized_base = actual_inflow * (30.0 / 28.0)
        else:
            normalized_base = float(actual_inflow)

        # Multi-month weighted moving average & momentum for New OPD
        m1 = hist_list[target_idx - 1]['total'] if target_idx >= 1 else actual_inflow
        m2 = hist_list[target_idx - 2]['total'] if target_idx >= 2 else m1
        m3 = hist_list[target_idx - 3]['total'] if target_idx >= 3 else m2

        # Grounded recent run-rate model: 85% current active pace (normalized), 15% previous month
        # This prevents past outlier months (like July festival promotions) from distorting realistic operational targets.
        pred_raw = 0.85 * normalized_base + 0.15 * m1
        pred_total = int(max(1 if actual_inflow > 0 or m1 > 0 else 0, round(pred_raw)))

        # Also project Old / Follow-up OPD visits to provide complete Grand Total OPD forecast
        actual_old = baseline_point.get('total_old', 0)
        norm_old = actual_old * (30.0 / 28.0) if active_baseline_month == '2026-09' else float(actual_old)
        old_m1 = hist_list[target_idx - 1].get('total_old', actual_old) if target_idx >= 1 else actual_old
        pred_old_raw = 0.55 * norm_old + 0.45 * old_m1
        pred_old_total = int(max(0, round(pred_old_raw)))

        # Grand Total OPD (New Patients + Follow-up / Old Visits)
        pred_grand_total = pred_total + pred_old_total
        target_grand_total = int(round(pred_grand_total * (1.0 + growth_rate)))
        if pred_grand_total > 0 and target_grand_total <= pred_grand_total:
            target_grand_total = pred_grand_total + 1

        weekly_pred_grand = round(pred_grand_total / 4.33, 1)
        weekly_target_grand = max(int(np.ceil(weekly_pred_grand)), int(round(target_grand_total / 4.33)))
        daily_pred_grand = round(pred_grand_total / 26.0, 1)
        daily_target_grand = max(int(np.ceil(daily_pred_grand)), int(round(target_grand_total / 26.0)))

        # Category shares based on recent 3-month volume
        tot_recent = sum(h['total'] for h in hist_list[max(0, target_idx - 2): target_idx + 1])
        ivf_recent = sum(h['new_ivf'] for h in hist_list[max(0, target_idx - 2): target_idx + 1])
        inf_recent = sum(h['new_inf'] for h in hist_list[max(0, target_idx - 2): target_idx + 1])
        anc_recent = sum(h['new_anc'] for h in hist_list[max(0, target_idx - 2): target_idx + 1])
        gyn_recent = sum(h['new_gynec'] for h in hist_list[max(0, target_idx - 2): target_idx + 1])

        safe_tot = max(1, tot_recent if tot_recent > 0 else actual_inflow)
        pred_ivf = int(round(pred_total * (ivf_recent / safe_tot)))
        pred_inf = int(round(pred_total * (inf_recent / safe_tot)))
        pred_anc = int(round(pred_total * (anc_recent / safe_tot)))
        pred_gyn = int(round(pred_total * (gyn_recent / safe_tot)))

        # Balance rounding
        cat_sum = pred_ivf + pred_inf + pred_anc + pred_gyn
        diff = pred_total - cat_sum
        if diff != 0:
            if pred_inf >= pred_ivf:
                pred_inf = max(0, pred_inf + diff)
            else:
                pred_ivf = max(0, pred_ivf + diff)

        # Channel breakdown
        onl_recent = sum(h['online'] for h in hist_list[max(0, target_idx - 2): target_idx + 1])
        led_recent = sum(h['lead'] for h in hist_list[max(0, target_idx - 2): target_idx + 1])
